import assert from "node:assert/strict";
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,readdirSync,rmSync} from "node:fs";
import {join,resolve} from "node:path";
import {createServer} from "node:net";
import {createRequire} from "node:module";
import {tmpdir,networkInterfaces} from "node:os";
import {setTimeout as delay} from "node:timers/promises";
import {startAgentLanGateway} from "../vendor/waishnav-devspace/dist/agent-lan-gateway.js";
const require=createRequire(import.meta.url);
const {readRuntimeJson}=require("./runtime-json.cjs");
const reverse=require("./ssh-reverse-tunnel.cjs");
const root=mkdtempSync(join(tmpdir(),"devspace-crash-test-"));
const configDir=join(root,"data","config");
const runDir=join(root,"data","run");
const prior=process.env.DEVSPACE_CONFIG_DIR;
const priorPortable=process.env.DEVSPACE_PORTABLE_CONFIG_DIR;
const priorRun=process.env.DEVSPACE_PORTABLE_RUN_DIR;
let gateway, blocker;
try {
  mkdirSync(configDir,{recursive:true});
  mkdirSync(join(runDir,"computer-use"),{recursive:true});
  process.env.DEVSPACE_CONFIG_DIR=configDir;
  process.env.DEVSPACE_PORTABLE_CONFIG_DIR=configDir;
  process.env.DEVSPACE_PORTABLE_RUN_DIR=runDir;
  const manager=require("./portable-manager.cjs");
  for(const file of [join(runDir,"ui-session.json"),join(runDir,"computer-use","broker.json")]){
    const corrupt=Buffer.alloc(365);
    writeFileSync(file,corrupt);
    assert.equal(manager.readJson(file,null),null);
    assert.equal(readRuntimeJson(file,null),null);
    const backup=readdirSync(join(file,"..")).filter(name=>name.startsWith(file.split(/[\\/]/).at(-1)+".corrupt-"));
    assert.equal(backup.length,1);
    assert.deepEqual(readFileSync(join(file,"..",backup[0])),corrupt);
    writeFileSync(file,JSON.stringify({ok:true}));
    assert.deepEqual(readRuntimeJson(file,null),{ok:true});
  }
  const key="name:recovery";
  reverse.writeEntry(root,{key,localHost:"192.168.1.2",localPort:7677,remotePort:19389});
  const badState=join(reverse.locations(root).run,reverse.keyId(key)+".json");
  mkdirSync(reverse.locations(root).run,{recursive:true});writeFileSync(badState,"\0\0");
  assert.equal(reverse.status(root,key).active,false);
  assert.equal(reverse.status(root,key).remotePort,19389);
  assert.equal(readdirSync(reverse.locations(root).run).filter(x=>x.includes(".corrupt-")).length,1);
  // Corrupt persistent SSH configuration must not silently reset credentials/settings.
  writeFileSync(reverse.locations(root).config,"\0");
  assert.throws(()=>reverse.entries(root),SyntaxError);
  blocker=createServer();
  await new Promise((resolve,reject)=>{blocker.once("error",reject);blocker.listen(0,"0.0.0.0",resolve);});
  const port=blocker.address().port;
  writeFileSync(join(configDir,"agent-network.json"),JSON.stringify({enabled:true,port,bindHosts:["0.0.0.0"]}));
  let attached=0;
  gateway=await startAgentLanGateway({stateDir:join(root,"data","state")},{attachHttpServer(){attached++;}},{retryMs:30});
  assert.deepEqual(gateway.status().active,[]);
  assert.equal(attached,0);
  await new Promise(resolve=>blocker.close(resolve));blocker=null;
  const deadline=Date.now()+3000;
  while(!gateway.status().active.length&&Date.now()<deadline)await delay(30);
  assert.deepEqual(gateway.status().active,["0.0.0.0"]);
  assert.equal(attached,1);
  assert.equal((await fetch("http://127.0.0.1:"+port+"/mcp")).status,404);
  await new Promise((resolve,reject)=>gateway.close(e=>e?reject(e):resolve()));gateway=null;
  const hosts=Object.values(networkInterfaces()).flat().map(item=>item.address);
  const missing=Array.from({length:254},(_,i)=>"192.168.254."+(i+1)).find(host=>!hosts.includes(host));
  writeFileSync(join(configDir,"agent-network.json"),JSON.stringify({enabled:true,port,bindHosts:[missing]}));
  gateway=await startAgentLanGateway({stateDir:join(root,"data","state")},{attachHttpServer(){}},{retryMs:30});
  assert.deepEqual(gateway.status().unavailable,[missing]);
  assert.deepEqual(gateway.status().active,["127.0.0.1"]);
  assert.equal((await fetch("http://127.0.0.1:"+port+"/agent/v1/install.sh")).status,200);
  assert.equal((await fetch("http://127.0.0.1:"+port+"/mcp")).status,404);
  await new Promise((resolve,reject)=>gateway.close(e=>e?reject(e):resolve()));gateway=null;
  console.log("PASS: corrupt volatile JSON, deduplicated byte backup, strict persistent config, all LAN binds unavailable, automatic retry, MCP isolation");
}finally{
  if(gateway)await new Promise(resolve=>gateway.close(resolve));
  if(blocker)await new Promise(resolve=>blocker.close(resolve));
  if(prior===undefined)delete process.env.DEVSPACE_CONFIG_DIR;else process.env.DEVSPACE_CONFIG_DIR=prior;
  if(priorPortable===undefined)delete process.env.DEVSPACE_PORTABLE_CONFIG_DIR;else process.env.DEVSPACE_PORTABLE_CONFIG_DIR=priorPortable;
  if(priorRun===undefined)delete process.env.DEVSPACE_PORTABLE_RUN_DIR;else process.env.DEVSPACE_PORTABLE_RUN_DIR=priorRun;
  rmSync(root,{recursive:true,force:true});
}
